/**
 * Fork divergence guard.
 *
 * Enforces the Volt fork invariant: **we never modify or delete opencode
 * upstream source — Volt is purely additive** (product in `packages/volt-*`,
 * plus new files at opencode's extension points). The only upstream files
 * we are allowed to touch are a small, explicit set of integration seams.
 *
 * This script is the always-accurate answer to "where do the fork's changes
 * live?" — it lists every upstream file the fork modified/deleted and fails
 * if any is outside the allowlist. Run it after every `git merge upstream/dev`.
 *
 *   bun run volt-scripts/check-divergence.ts            # compare against upstream/dev
 *   bun run volt-scripts/check-divergence.ts upstream/main
 *   bun run volt-scripts/check-divergence.ts --self-test # test the classifier logic (no git/env needed)
 *
 * Exit 0 = clean (only allowlisted seams touched); exit 1 = a new divergence
 * appeared (an edit/delete to upstream source) — investigate before merging.
 */
import { execSync } from "node:child_process"

// The ONLY upstream files the fork may modify. Everything else upstream must
// stay byte-identical; all Volt code is additive (new files / volt-* packages).
const ALLOWED_MODIFICATIONS = new Set<string>([
  "bun.lock", // workspace deps for the volt-* packages (regenerated by `bun install`)
  ".husky/pre-push", // scope the pre-push typecheck to volt-* packages
  ".gitignore", // local `/memory` Claude-memory junction ignore
  ".opencode/tui.json", // select the Volt brand theme (TUI theme is configured here, not in opencode.jsonc)
  // ── branding seams (Volt white-label; no additive hook exists for these) ──
  "packages/ui/src/components/logo.tsx", // Volt logo (bolt mark + wordmark)
  "packages/desktop/src/main/index.ts", // Volt app name
  "packages/desktop/electron-builder.config.ts", // Volt productName / protocol display name
])

// Paths that are wholly fork-owned — changes here never count as divergence.
// `.claude/` (BMAD skills) and `_bmad/` (BMAD framework) are committed dev tooling;
// they don't exist upstream, so additions there are additive, never a divergence.
const FORK_OWNED_PREFIXES = ["packages/volt-", "volt-scripts/", ".claude/", "_bmad/"]

// Committed-junk patterns — backups, merge leftovers, OS/editor cruft. Flagged anywhere in
// the fork's tracked changes (even fork-owned dirs), so accidents (`.tsproj.bak`, `.DS_Store`,
// `*.orig` merge leftovers) don't slip in. Upstream's own junk never appears in our diff, so
// it's untouched.
const JUNK_FILE = /\.(bak|orig|swp)$|(^|\/)(\.DS_Store|Thumbs\.db|desktop\.ini)$|~$/i

// Individual fork files added at opencode's extension points — they have a forced
// home outside packages/ (Claude Code auto-loads CLAUDE.md at the repo root; opencode
// discovers agents only from .opencode/agent/). A NEW file is exempt only if it is
// fork-owned OR explicitly listed here; anything else added (into .github/, .claude/,
// .opencode/skills/, scratch/, new root files, …) is a divergence.
const ADDITIVE_ALLOWLIST = new Set<string>([
  "CLAUDE.md",
  "NOTICE", // MIT attribution for the opencode fork
  "VOLT-ROADMAP.md", // Volt-as-a-SaaS plan-of-record (companion to CLAUDE.md)
  "VOLT-DECISIONS.md", // Volt decision log (ADRs)
  ".opencode/agent/volt.md",
  ".opencode/themes/volt.json", // Volt brand theme (selected via the .opencode/tui.json seam)
  ".opencode/tool/volt.ts", // Volt CLI exposed as an opencode custom tool (opencode scans .opencode/tool/ only)
  ".opencode/opencode.json", // Volt config (LSP + permission gates) — opencode deep-merges it over upstream's pristine opencode.jsonc
  // Future graphical Volt panel for the TUI lands at `.opencode/plugins/volt.tsx` — allowlist it here when it does.
])

// Prefixes under which fork-added files are allowed (Volt-namespaced files in upstream dirs).
const ADDITIVE_PREFIXES = [".github/workflows/volt-"] // Volt's own CI / scheduled-sync workflows

function isForkOwned(path: string): boolean {
  return FORK_OWNED_PREFIXES.some((p) => path.startsWith(p))
}

export interface Classification {
  allowed: string[] // allowlisted seam edits (expected)
  violations: string[] // edits/deletes of upstream source (forbidden)
}

/**
 * Pure classifier — the heart of the guard. Takes `git diff --name-status`
 * lines and buckets each into allowed / violation (additive + fork-owned are
 * silently exempt). No I/O, so it is unit-tested by `--self-test`.
 */
export function classify(nameStatusLines: readonly string[]): Classification {
  const allowed: string[] = []
  const violations: string[] = []

  for (const line of nameStatusLines) {
    if (line.trim() === "") continue
    const fields = line.split("\t")
    const code = (fields[0] ?? "").charAt(0)
    // For rename/copy (R/C) git emits old\tnew — the destination is the last field.
    const path = code === "R" || code === "C" ? (fields[fields.length - 1] ?? "") : fields.slice(1).join("\t")

    // Committed junk anywhere in the fork's files is a violation (a deletion is fine — that
    // *removes* junk). Checked before the fork-owned exemption so cruft in volt-*/.claude/… is caught.
    if (code !== "D" && JUNK_FILE.test(path)) {
      violations.push(`junk ${code}  ${path}`)
      continue
    }

    if (isForkOwned(path)) continue // volt-* packages / volt-scripts — additive, exempt

    // A NEW file (didn't exist upstream) is additive-fine only at a sanctioned location.
    if (code === "A") {
      if (ADDITIVE_ALLOWLIST.has(path) || ADDITIVE_PREFIXES.some((p) => path.startsWith(p))) continue
      violations.push(`${code}  ${path}`) // added outside the fork surface — a divergence
      continue
    }

    // M/D/R/C of an upstream-tracked file: only allowlisted seams are OK.
    if (ALLOWED_MODIFICATIONS.has(path)) allowed.push(`${code}  ${path}`)
    else violations.push(`${code}  ${path}`)
  }

  return { allowed, violations }
}

// ─── Self-test (run the classifier against synthetic diffs; no git needed) ───

function selfTest(): void {
  const cases: { name: string; lines: string[]; allowed: number; violations: number }[] = [
    { name: "volt package edit is exempt", lines: ["M\tpackages/volt-cli/src/x.ts"], allowed: 0, violations: 0 },
    { name: "volt-scripts edit is exempt", lines: ["M\tvolt-scripts/check-divergence.ts"], allowed: 0, violations: 0 },
    { name: "allowlisted additive files are fine", lines: ["A\tCLAUDE.md", "A\tNOTICE", "A\tVOLT-ROADMAP.md", "A\tVOLT-DECISIONS.md", "A\t.opencode/agent/volt.md", "A\t.opencode/themes/volt.json", "A\t.opencode/tool/volt.ts", "A\t.opencode/opencode.json"], allowed: 0, violations: 0 },
    { name: "branding seams (logo / app-name) count as allowed", lines: ["M\tpackages/ui/src/components/logo.tsx", "M\tpackages/desktop/src/main/index.ts", "M\tpackages/desktop/electron-builder.config.ts"], allowed: 3, violations: 0 },
    { name: "Volt-namespaced CI workflow is allowed (prefix)", lines: ["A\t.github/workflows/volt-ci.yml"], allowed: 0, violations: 0 },
    { name: "other committed theme is a violation (only volt.json is sanctioned)", lines: ["A\t.opencode/themes/other.json"], allowed: 0, violations: 1 },
    { name: "a non-volt .github workflow is a violation", lines: ["A\t.github/workflows/evil.yml"], allowed: 0, violations: 1 },
    { name: "added file outside the surface is a violation (scratch)", lines: ["A\tscratch/.gitignore"], allowed: 0, violations: 1 },
    { name: "committed skill is a violation (skills are generated, not committed)", lines: ["A\t.opencode/skills/x/SKILL.md"], allowed: 0, violations: 1 },
    { name: "allowed seams count as allowed", lines: ["M\t.husky/pre-push", "M\t.gitignore", "M\tbun.lock", "M\t.opencode/tui.json"], allowed: 4, violations: 0 },
    { name: "opencode.jsonc edit is now a violation (config moved to opencode.json merge-layer)", lines: ["M\t.opencode/opencode.jsonc"], allowed: 0, violations: 1 },
    { name: "root turbo.json edit is now a violation (test tasks moved per-package)", lines: ["M\tturbo.json"], allowed: 0, violations: 1 },
    { name: "upstream source edit is a violation", lines: ["M\tpackages/opencode/src/lsp/server.ts"], allowed: 0, violations: 1 },
    { name: "upstream file delete is a violation", lines: ["D\tpackages/core/src/foo.ts"], allowed: 0, violations: 1 },
    { name: "renamed upstream file is a violation (dest path)", lines: ["R100\tpackages/core/a.ts\tpackages/core/b.ts"], allowed: 0, violations: 1 },
    { name: "mixed real-world set", lines: ["M\tbun.lock", "A\tvolt-scripts/x.ts", "M\tpackages/volt-lsp-st/src/y.ts", "M\tpackages/server/src/z.ts"], allowed: 1, violations: 1 },
    { name: "committed junk in a fork-owned path is a violation", lines: ["A\tpackages/volt-bridge/test/x.tsproj.bak"], allowed: 0, violations: 1 },
    { name: "OS/editor cruft is a violation", lines: ["A\tpackages/volt-cli/.DS_Store"], allowed: 0, violations: 1 },
    { name: "deleting junk is fine (not a violation)", lines: ["D\tpackages/volt-bridge/test/x.tsproj.bak"], allowed: 0, violations: 0 },
  ]

  let failed = 0
  for (const c of cases) {
    const got = classify(c.lines)
    const ok = got.allowed.length === c.allowed && got.violations.length === c.violations
    console.log(`  ${ok ? "✓" : "✗"} ${c.name}`)
    if (!ok) {
      failed++
      console.log(`      expected allowed=${c.allowed} violations=${c.violations}, got allowed=${got.allowed.length} violations=${got.violations.length}`)
    }
  }
  if (failed > 0) {
    console.log(`\n✗ classifier self-test: ${failed} case(s) failed`)
    process.exit(1)
  }
  console.log(`\n✓ classifier self-test passed (${cases.length} cases)`)
}

// ─── Entry point ─────────────────────────────────────────────────────────

function main(): void {
  const arg = process.argv[2]
  if (arg === "--self-test") {
    selfTest()
    return
  }

  const upstreamRef = arg ?? "upstream/dev"

  // Skip gracefully when the upstream ref isn't present (fresh clone, CI without
  // the upstream remote, or `git fetch upstream` not run). Never block on it.
  try {
    execSync(`git rev-parse --verify --quiet ${upstreamRef}`, { stdio: "ignore" })
  } catch {
    console.log(`⊘ skipped — ref '${upstreamRef}' not found. Run \`git fetch upstream\` to enable the divergence check.`)
    return
  }

  const out = execSync(`git diff --name-status ${upstreamRef} HEAD`, { encoding: "utf8" })
  const { allowed, violations } = classify(out.split("\n"))

  console.log(`Fork divergence vs ${upstreamRef}\n`)
  console.log(`Allowed integration seams touched (${allowed.length}):`)
  for (const a of allowed) console.log(`  ${a}`)

  if (violations.length > 0) {
    console.log(`\n✗ UNEXPECTED upstream-source divergence (${violations.length}) — Volt must be additive:`)
    for (const v of violations) console.log(`  ${v}`)
    console.log(`\nEither revert these to upstream, or (if intentional) add them to ALLOWED_MODIFICATIONS in this script.`)
    process.exit(1)
  }

  console.log(`\n✓ clean — no upstream source modified outside the ${ALLOWED_MODIFICATIONS.size} allowed seams.`)
}

main()
