/**
 * Network-twin recorder (openspec network-text-st 2.4, design.md oracle 3) — every LD/FBD body of a corpus project, as
 * the plain-ST network text a pull writes it, compiled by the IDE as its EXEC TWIN: the CODESYS ST that runs as the
 * network (`test/support/network-twin.ts`). Writes `test-corpus/<PROJECT>/network-twins.<vendor>.json` — the build of the
 * project with every network body replaced by its twin, in place — which `test/corpus/corpus-twins.test.ts` holds to the
 * project's own recorded build: a twin that does not compile is a network text the LSP and the push read as something
 * CODESYS would not run.
 *
 *   pwsh packages/volt-cli/scripts/ide.ps1 up -Vendor codesys -Instance <name> -Fixture "<the corpus's .project>" -Wait
 *   PROJECT=lenze-mid VOLT_VENDOR=codesys VOLT_E2E_INSTANCE=<name> bun run scripts/record-network-twins.ts
 *   pwsh packages/volt-cli/scripts/ide.ps1 down -Vendor codesys -Instance <name>
 *
 * The instance serves a COPY of the project (`ide.ps1` never serves the file itself), so the push changes nothing kept:
 * each twinned item is set as its twin (CODESYS changes a body's language in place, DIALECT N24), the project built, the
 * diagnostics written down. Which `.project` a corpus is pulled from: `refresh-corpus.ts`.
 */
import { writeFileSync } from "node:fs"
import { join } from "node:path"
import { call, landedInFull, target, VENDOR } from "./bridge.js"
import { twinProject } from "../test/support/network-twin-project.js"

const PROJECT = process.env.PROJECT
if (PROJECT === undefined) throw new Error("set PROJECT=<corpus folder name> (e.g. lenze-mid)")
const dir = join(import.meta.dir, "..", "test-corpus", PROJECT)

const twins = twinProject(dir, VENDOR)
if (twins.refused.length > 0) throw new Error(`the twin cannot write ${twins.refused.length} body(ies):\n  ${twins.refused.join("\n  ")}`)
console.log(`${PROJECT}: ${twins.bodies} network bodies in ${twins.files.length} items, twinned (${twins.hash}); pushing on ${target()} …`)

const refs = await call("refs")
const missing = twins.files.filter((f) => refs.items?.[f.wire] === undefined)
if (missing.length > 0) throw new Error(`the served project holds no ${missing.map((f) => f.wire).join(", ")}: is it ${PROJECT}'s project?`)
const pushed = await call("push", {
  expectedProjectVersion: refs.projectVersion,
  ops: twins.files.map((f) => ({ op: "set", name: f.wire, sourceText: f.source, ifVersion: refs.items[f.wire] })),
})
// a push that did not land in full is no build of the twins (`record-language.ts` `pushOps`)
if (!landedInFull(pushed)) throw new Error(`the twins did not land in full:\n  ${JSON.stringify(pushed.conflicts ?? pushed)}`)

const r = await call("build", {})
const diagnostics = (r.diagnostics ?? [])
  .filter((d: any) => d.severity === "error" || d.severity === "warning")
  .map((d: any) => ({ severity: d.severity, message: String(d.message), object: d.object ?? d.path ?? "", line: d.line ?? 0 }))
const out = {
  _doc: "The build of this corpus project with every LD/FBD body as its exec twin. Generated by scripts/record-network-twins.ts — re-record when a network body or the twin changes. Read by test/corpus/corpus-twins.test.ts.",
  recorded: { at: new Date().toISOString(), vendor: VENDOR, buildSuccess: !!r.success, twins: twins.hash, bodies: twins.bodies, items: twins.files.length },
  diagnostics,
}
writeFileSync(join(dir, `network-twins.${VENDOR}.json`), JSON.stringify(out, null, 2) + "\n")
console.log(`build ${r.success ? "succeeded" : "FAILED"}: ${diagnostics.filter((d: any) => d.severity === "error").length} error(s), ${diagnostics.length} diagnostic(s) → network-twins.${VENDOR}.json`)
