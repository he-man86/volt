/**
 * The refused-word lists are the MEASUREMENTS, held to them: every word a live IDE refused as an object's name in the
 * `refused-names` fact of volt-cli's `scripts/vendor-facts.<vendor>.json` (the same snapshot volt-cli's Repo.Gates
 * `RefusedNamesMatchTheSnapshotTests` holds the drivers' lists to). `VOLT_WRITE_REFUSED_NAMES=1` regenerates the file.
 */
import { expect, test } from "bun:test"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { CODESYS_REFUSED_NAMES, TWINCAT_REFUSED_NAMES } from "./refused-names.js"

const SCRIPTS = join(import.meta.dir, "../../../../volt-cli/scripts")
const HERE = join(import.meta.dir, "refused-names.ts")

/** Every word the snapshot's `refused-names` groups refused, upper-cased, sorted, once. */
function refusedIn(vendor: "codesys" | "twincat"): string[] {
  const fact = JSON.parse(readFileSync(join(SCRIPTS, `vendor-facts.${vendor}.json`), "utf8"))["refused-names"] as Record<string, unknown>
  const words = new Set<string>()
  for (const [group, verdicts] of Object.entries(fact)) {
    if (group === "steps") continue
    for (const w of (verdicts as { refused: string[] }).refused) words.add(w.toUpperCase())
  }
  return [...words].sort()
}

function render(codesys: readonly string[], twincat: readonly string[]): string {
  const list = (words: readonly string[]) => {
    const lines: string[] = []
    for (let i = 0; i < words.length; i += 8) lines.push(`  ${words.slice(i, i + 8).map((w) => JSON.stringify(w)).join(", ")},`)
    return lines.join("\n")
  }
  return `// GENERATED by refused-names.test.ts (VOLT_WRITE_REFUSED_NAMES=1) from volt-cli scripts/vendor-facts.<vendor>.json, fact
// \`refused-names\` — do not edit; re-measure and regenerate.
/**
 * EVERY WORD EACH IDE REFUSED, LIVE, AS THE NAME OF A NEW OBJECT — a POU, a METHOD, an ACTION, a PROPERTY (openspec
 * push-keeps-what-landed 3.1; volt-cli's drivers pre-flight a push by the same snapshot). Upper case: both IDEs refuse a
 * word whatever its case (the snapshot's casing groups measured it).
 */
export const CODESYS_REFUSED_NAMES: ReadonlySet<string> = new Set([
${list(codesys)}
])

export const TWINCAT_REFUSED_NAMES: ReadonlySet<string> = new Set([
${list(twincat)}
])
`
}

test("each vendor's list is every word its snapshot refused", () => {
  const codesys = refusedIn("codesys")
  const twincat = refusedIn("twincat")
  if (process.env.VOLT_WRITE_REFUSED_NAMES === "1") writeFileSync(HERE, render(codesys, twincat))
  expect([...CODESYS_REFUSED_NAMES]).toEqual(codesys)
  expect([...TWINCAT_REFUSED_NAMES]).toEqual(twincat)
  // the measurement the model rests on, by name
  expect(CODESYS_REFUSED_NAMES.has("INT") && TWINCAT_REFUSED_NAMES.has("INT")).toBe(true)
  expect(CODESYS_REFUSED_NAMES.has("GET") || TWINCAT_REFUSED_NAMES.has("GET")).toBe(false)
})
